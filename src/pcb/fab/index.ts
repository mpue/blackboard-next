export interface FabricationOptions {
  project: string;
  zoneFills?: ZoneFills;
  /** board units, default 0.05 mm */
  maskExpansion?: number;
}

const DESCRIPTIONS: [string, string][] = [
  ['-F_Cu.gtl', 'Top copper (L1)'],
  ['-B_Cu.gbl', 'Bottom copper (L2)'],
  ['-F_Mask.gts', 'Top solder mask, openings (negative)'],
  ['-B_Mask.gbs', 'Bottom solder mask, openings (negative)'],
  ['-F_Silkscreen.gto', 'Top silkscreen (legend)'],
  ['-B_Silkscreen.gbo', 'Bottom silkscreen (legend)'],
  ['-Edge_Cuts.gm1', 'Board outline (profile)'],
  ['-PTH.drl', 'Plated holes: THT pads and vias (Excellon)'],
  ['-NPTH.drl', 'Non plated holes (Excellon)'],
  ['-pos.csv', 'Pick and place: footprint origins in mm, rotation counter clockwise'],
  ['-bom.csv', 'Bill of materials, grouped by value and footprint'],
];

function readme(doc: Doc, project: string, files: FabFile[]): string {
  const width = Math.max(...files.map((f) => f.name.length));
  const layers = doc.pcb?.rules.copperLayers ?? 2;
  return [
    `${project} - fabrication data`,
    'Generated by BlackBoard Next 3.0',
    '',
    `Board: ${toMm(doc.width).toFixed(2)} x ${toMm(doc.height).toFixed(2)} mm, ${layers} copper layer${layers > 1 ? 's' : ''}`,
    'Gerber RS-274X with X2 attributes, format 4.6, unit mm.',
    'Excellon drill files, metric, decimal coordinates.',
    'Origin: lower left corner of the board. All layers are seen from the top,',
    'bottom layers are not mirrored. Vias are tented (covered by solder mask).',
    '',
    'Files:',
    ...files.map((f) => `  ${f.name.padEnd(width)}  ${DESCRIPTIONS.find(([s]) => f.name.endsWith(s))?.[1] ?? ''}`.trimEnd()),
    '',
  ].join('\n');
}

/** Every fabrication file incl. README.txt. */
export function fabricationFiles(doc: Doc, opts: FabricationOptions): FabFile[] {
  const p = safeProjectName(opts.project);
  const files: FabFile[] = [
    ...gerberFiles(doc, { project: p, zoneFills: opts.zoneFills, maskExpansion: opts.maskExpansion }),
    ...drillFiles(doc, p),
    { name: `${p}-pos.csv`, content: pickAndPlaceCsv(doc) },
    { name: `${p}-bom.csv`, content: bomCsv(doc) },
  ];
  return [...files, { name: 'README.txt', content: readme(doc, p, files) }];
}

export function fabricationZip(doc: Doc, opts: FabricationOptions): Uint8Array {
  const entries: Record<string, Uint8Array> = {};
  for (const f of fabricationFiles(doc, opts)) entries[f.name] = strToU8(f.content);
  return zipSync(entries, { level: 6 });
}
