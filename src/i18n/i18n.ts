const dicts = { de, en };

export function translate(lang: 'de' | 'en', key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = dicts[lang][key] ?? de[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (key: I18nKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function t(key: I18nKey, vars?: Record<string, string | number>) {
  return translate(useStore.getState().settings.lang, key, vars);
}
