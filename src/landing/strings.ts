export type Lang = 'de' | 'en';
export type LandingKey = Key;

/** The language of the editor's settings, else of the browser. */
export function landingLang(): Lang {
  try {
    const s = JSON.parse(localStorage.getItem('blackboard.settings.v1') ?? '{}') as { lang?: string };
    if (s.lang === 'de' || s.lang === 'en') return s.lang;
  } catch {
    // no storage
  }
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en';
}

export function setLandingLang(lang: Lang) {
  try {
    const s = JSON.parse(localStorage.getItem('blackboard.settings.v1') ?? '{}') as Record<string, unknown>;
    localStorage.setItem('blackboard.settings.v1', JSON.stringify({ ...s, lang }));
  } catch {
    // no storage
  }
}

export function translator(lang: Lang) {
  const dict = lang === 'de' ? de : en;
  return (key: Key, vars: Record<string, string> = {}) => dict[key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? '');
}

export type T = ReturnType<typeof translator>;
